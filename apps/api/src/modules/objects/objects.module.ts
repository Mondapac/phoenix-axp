/** Each use case built with the gate and its unit first and its ports after. */
function useCase(type: abstract new (...args: never[]) => unknown, inject: unknown[]): Provider {
  return {
    provide: type,
    inject: [USE_CASE_GATE, UNIT_OF_WORK, ...inject] as never[],
    useFactory: (...deps: unknown[]) =>
      new (type as unknown as new (...args: unknown[]) => unknown)(...deps),
  };
}

const DEFINITIONS = DEFINITION_REPOSITORY;
const RECORDS = RECORD_REPOSITORY;
const REACH = DEFINITION_REACH;
const ACCESS = RECORD_ACCESS;
const KEYS = SUBJECT_KEY_SERVICE;

/**
 * The objects module (Phase 2 slice 2.8, ADR-0017): Object definitions with immutable
 * revisions and stable field ids, and their records behind a REST API generated by data, with
 * record-level access by site and field-level access through FieldPolicy (ADR-0024). Site,
 * grant and field-rule questions go through platform/authz's ports.
 */
@Module({
  controllers: [ObjectDefinitionsController, ObjectRecordsController],
  providers: [
    registerPermissions('objects', OBJECTS_PERMISSIONS),
    registerAuditActions('objects', OBJECTS_AUDIT_ACTIONS),
    PersistenceModule.auditWriterFor('objects'),
    { provide: DEFINITIONS, useClass: PrismaDefinitionRepository },
    { provide: RECORDS, useClass: PrismaRecordRepository },
    {
      provide: REACH,
      inject: [UNIT_OF_WORK, DEFINITIONS, ACTOR_GRANT_READER, SITE_ANCESTRY_READER],
      useFactory: (
        unitOfWork: UnitOfWork,
        definitions: DefinitionRepository,
        grants: ActorGrantReader,
        sites: SiteAncestryReader,
      ) => new DefinitionReach(unitOfWork, definitions, grants, sites),
    },
    {
      provide: ACCESS,
      inject: [FIELD_RULE_READER, SITE_ANCESTRY_READER],
      useFactory: (rules: FieldRuleReader, sites: SiteAncestryReader) =>
        new RecordAccess(rules, sites),
    },
    useCase(ListDefinitions, [DEFINITIONS, REACH]),
    useCase(ViewDefinition, [DEFINITIONS, REACH]),
    useCase(ViewRevision, [DEFINITIONS, REACH]),
    useCase(CreateDefinition, [
      DEFINITIONS,
      REACH,
      SITE_ANCESTRY_READER,
      AUDIT_WRITER,
      CLOCK,
      ID_GENERATOR,
    ]),
    useCase(RenameDefinition, [DEFINITIONS, REACH, AUDIT_WRITER, CLOCK]),
    useCase(SaveRevision, [DEFINITIONS, REACH, AUDIT_WRITER, CLOCK, ID_GENERATOR]),
    useCase(PublishDefinition, [DEFINITIONS, REACH, AUDIT_WRITER, CLOCK]),
    useCase(RetireDefinition, [DEFINITIONS, REACH, AUDIT_WRITER, CLOCK]),
    useCase(DescribeObject, [DEFINITIONS, ACCESS]),
    useCase(ListRecords, [DEFINITIONS, RECORDS, ACCESS, KEYS]),
    useCase(ViewRecord, [DEFINITIONS, RECORDS, ACCESS, KEYS]),
    useCase(CreateRecord, [DEFINITIONS, RECORDS, ACCESS, KEYS, AUDIT_WRITER, CLOCK, ID_GENERATOR]),
    useCase(UpdateRecord, [DEFINITIONS, RECORDS, ACCESS, KEYS, AUDIT_WRITER, CLOCK]),
    useCase(DeleteRecord, [DEFINITIONS, RECORDS, ACCESS, KEYS, AUDIT_WRITER, CLOCK]),
    useCase(SealRecords, [DEFINITIONS, RECORDS, KEYS, AUDIT_WRITER]),
    registerJobsFrom('objects', [SealRecords], (seal: SealRecords) => [sealRecordsJob(seal)]),
  ],
})
export class ObjectsModule {}
